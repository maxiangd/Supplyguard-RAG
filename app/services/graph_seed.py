# 关系类型交替写意味着 Cypher 里没法把类型当参数，这里按类型准备语句
EDGE_QUERIES = {
    relation: (
        "MATCH (a:Entity {id: $source}), (b:Entity {id: $target}) "
        f"MERGE (a)-[r:{relation}]->(b) "
        "SET r += $props"
    )
    for relation in {edge["relation"] for edge in EDGES}
}

IMPACT_QUERY = (
    "MATCH (e:Entity {id: $event}), (t:Entity {id: $target}) "
    "MERGE (e)-[r:AFFECTS]->(t) SET r.rule = $rule, "
    "r.severity = $severity, r.reason = $reason"
)


def seed_graph() -> dict:
    """幂等写入全部演示节点与关系，重复执行只会更新属性。"""
    for statement in CONSTRAINTS:
        run_write(statement)

    for node in NODES:
        run_write(
            "MERGE (n:Entity {id: $id}) SET n += $props",
            {"id": node["id"], "props": node},
        )

    for edge in EDGES:
        properties = {key: value for key, value in edge.items() if key not in ("source", "target", "relation")}
        run_write(
            EDGE_QUERIES[edge["relation"]],
            {"source": edge["source"], "target": edge["target"], "props": properties},
        )

    for impact in IMPACTS:
        run_write(IMPACT_QUERY, impact)

    return {"nodes": len(NODES), "relations": len(EDGES) + len(IMPACTS)}


